import json
import logging
from pathlib import Path

import geopandas as gpd
import pytest
from shapely.geometry import Polygon

from data_pipeline.processing.geo import process_boundaries


def _write_test_shapefile(tmp_path: Path, records: list[dict]) -> Path:
    shapefile_dir = tmp_path / "source"
    shapefile_dir.mkdir(parents=True, exist_ok=True)
    shapefile_path = shapefile_dir / "D_lowPopMap_A.shp"
    gdf = gpd.GeoDataFrame(records, crs="EPSG:4326").to_crs(epsg=3857)
    gdf.to_file(shapefile_path)
    return shapefile_path


def test_process_ssc_boundaries_generates_geojson_and_manifest(tmp_path: Path, caplog: pytest.LogCaptureFixture) -> None:
    shapefile_path = _write_test_shapefile(
        tmp_path,
        [
            {
                "SSC_CODE": "101",
                "SSC_NAME": "ALPHA HILL",
                "LGA_NAME": "BRISBANE INNER",
                "STATE": "qld",
                "AREA_SQKM": 10.5,
                "geometry": Polygon([(153.00, -27.00), (153.05, -27.00), (153.05, -26.95), (153.00, -26.95)]),
            },
            {
                "SSC_CODE": "102",
                "SSC_NAME": "BETA CREEK",
                "LGA_NAME": "BRISBANE INNER",
                "STATE": "qld",
                "AREA_SQKM": 12.25,
                "geometry": Polygon([(153.06, -27.00), (153.11, -27.00), (153.11, -26.95), (153.06, -26.95)]),
            },
            {
                "SSC_CODE": "201",
                "SSC_NAME": "GAMMA FLATS",
                "LGA_NAME": "DARLING DOWNS",
                "STATE": "qld",
                "AREA_SQKM": 8.75,
                "geometry": Polygon([(151.90, -28.10), (151.96, -28.10), (151.96, -28.04), (151.90, -28.04)]),
            },
        ],
    )
    boundaries_dir = tmp_path / "frontend" / "assets" / "geo" / "boundaries"
    manifest_path = tmp_path / "frontend" / "src" / "services" / "boundaries" / "sscManifest.ts"
    legacy_suburbs_dir = boundaries_dir / "suburbs"
    legacy_suburbs_dir.mkdir(parents=True, exist_ok=True)
    (legacy_suburbs_dir / "legacy.json").write_text("{}", encoding="utf-8")
    (boundaries_dir / "lga_boundaries.json").write_text("{}", encoding="utf-8")

    with caplog.at_level(logging.INFO, logger=process_boundaries.LOGGER.name):
        stats = process_boundaries.process_ssc_boundaries(
            shapefile_path=shapefile_path,
            out_dir=boundaries_dir,
            manifest_path=manifest_path,
        )

    assert stats["feature_count"] == 3
    assert stats["group_count"] == 2
    # Legacy assets are intentionally preserved until Story 1.2 switches BoundaryStore
    assert (boundaries_dir / "lga_boundaries.json").exists()
    assert legacy_suburbs_dir.exists()

    coarse_path = boundaries_dir / "ssc_coarse.json"
    detail_dir = boundaries_dir / "ssc"
    assert coarse_path.exists()
    assert detail_dir.exists()
    assert "\n" not in coarse_path.read_text(encoding="utf-8")

    coarse_collection = json.loads(coarse_path.read_text(encoding="utf-8"))
    assert coarse_collection["type"] == "FeatureCollection"
    assert {feature["properties"]["group_id"] for feature in coarse_collection["features"]} == {
        "group_brisbane_inner",
        "group_darling_downs",
    }

    brisbane_detail = json.loads((detail_dir / "group_brisbane_inner.json").read_text(encoding="utf-8"))
    assert brisbane_detail["type"] == "FeatureCollection"
    assert [feature["id"] for feature in brisbane_detail["features"]] == ["ssc_101", "ssc_102"]
    first_feature = brisbane_detail["features"][0]
    assert first_feature["properties"] == {
        "id": "ssc_101",
        "name": "Alpha Hill",
        "state": "QLD",
        "group_id": "group_brisbane_inner",
        "area_sqkm": pytest.approx(10.5),
    }
    assert first_feature["geometry"]["type"] == "Polygon"

    manifest_text = manifest_path.read_text(encoding="utf-8")
    assert manifest_text.startswith("// Auto-generated by process_boundaries.py - DO NOT EDIT\n")
    assert 'import { FeatureCollection } from "geojson";' in manifest_text
    assert 'export const sscCollections: Record<string, FeatureCollection> = {' in manifest_text
    assert (
        '"group_brisbane_inner": require("../../../assets/geo/boundaries/ssc/group_brisbane_inner.json"),'
        in manifest_text
    )
    assert (
        '"group_darling_downs": require("../../../assets/geo/boundaries/ssc/group_darling_downs.json"),'
        in manifest_text
    )

    assert any("Shapefile columns:" in message and "LGA_NAME" in message for message in caplog.messages)
    assert any("Processing completed in" in message for message in caplog.messages)
    assert any("Output file" in message for message in caplog.messages)


