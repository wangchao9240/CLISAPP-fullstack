def test_area_sqkm_computed_from_geometry_when_no_area_column(tmp_path: Path) -> None:
    """When shapefile has no area column, area_sqkm should be computed from geometry."""
    shapefile_path = _write_test_shapefile(
        tmp_path,
        [
            {
                "SSC_CODE": "101",
                "SSC_NAME": "ALPHA HILL",
                "LGA_NAME": "BRISBANE INNER",
                "geometry": Polygon([(153.00, -27.00), (153.05, -27.00), (153.05, -26.95), (153.00, -26.95)]),
            },
        ],
    )
    boundaries_dir = tmp_path / "frontend" / "assets" / "geo" / "boundaries"
    manifest_path = tmp_path / "frontend" / "src" / "services" / "boundaries" / "sscManifest.ts"

    process_boundaries.process_ssc_boundaries(
        shapefile_path=shapefile_path,
        out_dir=boundaries_dir,
        manifest_path=manifest_path,
    )

    detail_file = boundaries_dir / "ssc" / "group_brisbane_inner.json"
    detail = json.loads(detail_file.read_text(encoding="utf-8"))
    area = detail["features"][0]["properties"]["area_sqkm"]
    assert area is not None
    assert area > 0


def test_parse_args_defaults_and_overrides() -> None:
    """CLI argument parsing with defaults and overrides."""
    defaults = process_boundaries.parse_args([])
    assert defaults.shapefile == process_boundaries.SSC_SHP
    assert defaults.group_field is None
    assert defaults.simplify_tolerance == process_boundaries.SIMPLIFY_TOLERANCE

    custom = process_boundaries.parse_args([
        "--shapefile", "/tmp/test.shp",
        "--group-field", "SA3_NAME",
        "--simplify-tolerance", "0.001",
    ])
    assert custom.shapefile == Path("/tmp/test.shp")
    assert custom.group_field == "SA3_NAME"
    assert custom.simplify_tolerance == 0.001


def test_custom_simplify_tolerance_affects_output(tmp_path: Path) -> None:
    """Higher tolerance should produce simpler geometry (fewer coordinates)."""
    records = [
        {
            "SSC_CODE": "101",
            "SSC_NAME": "ALPHA HILL",
            "LGA_NAME": "BRISBANE",
            "geometry": Polygon([
                (153.00, -27.00), (153.01, -27.005), (153.02, -27.001),
                (153.03, -27.006), (153.04, -27.002), (153.05, -27.00),
                (153.05, -26.95), (153.00, -26.95),
            ]),
        },
    ]

    results = {}
    for label, tolerance in [("fine", 0.0001), ("coarse", 0.01)]:
        run_dir = tmp_path / label
        shapefile_path = _write_test_shapefile(run_dir, records)
        boundaries_dir = run_dir / "out"
        manifest_path = run_dir / "manifest" / "sscManifest.ts"
        process_boundaries.process_ssc_boundaries(
            shapefile_path=shapefile_path,
            out_dir=boundaries_dir,
            manifest_path=manifest_path,
            simplify_tolerance=tolerance,
        )
        coarse = json.loads((boundaries_dir / "ssc_coarse.json").read_text(encoding="utf-8"))
        results[label] = len(json.dumps(coarse))

    assert results["coarse"] <= results["fine"]


